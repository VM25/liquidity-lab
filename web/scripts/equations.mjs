// Render the paper's equations to HTML + MathML at build time (KaTeX), so the browser loads no maths library.
// Each TeX source is copied from docs/memo/The_Liquidity_Paradox.tex; src/data/equations.test.ts checks that.
import katex from 'katex';
import { writeFile } from 'node:fs/promises';

const EQ = [
  { id: 'spreads', tex: String.raw`\begin{aligned}
  es &= 2s\,\frac{P-m_0}{m_0}\times 10^4, \qquad mo(h) = s\,\frac{m_{T+h}-m_0}{m_0}\times 10^4,\\
  rs(h) &= es - 2\,mo(h) = 2s\,\frac{P-m_{T+h}}{m_0}\times 10^4 .
\end{aligned}` },
  { id: 'r2', tex: String.raw`\Rsq = 1 - \frac{\sum_k (y_k - \hat f_k)^2}{\sum_k y_k^2},` },
  { id: 'dw', tex: String.raw`D_W = q(W_P) - q(W_U),` },
  { id: 'rhoa', tex: String.raw`\rho_A=\sum A/\sum L` },
];
const macros = { '\\Rsq': 'R^2_{\\mathrm{OS}}' };
const out = Object.fromEntries(EQ.map((e) => [e.id, {
  tex: e.tex,
  html: katex.renderToString(e.tex, { displayMode: true, output: 'htmlAndMathml', throwOnError: true, macros: { ...macros } }),
}]));
await writeFile(new URL('../src/data/equations.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log(`wrote src/data/equations.json (${EQ.length} equations)`);

// KaTeX's stylesheet lists Times New Roman as a fallback, a family the owner's design rules exclude.
// Write a copy that falls back to Georgia instead, with its font URLs pointing at the installed KaTeX fonts.
import { readFile } from 'node:fs/promises';
const css = await readFile(new URL('../node_modules/katex/dist/katex.min.css', import.meta.url), 'utf8');
const site = css.replace(/Times New Roman/g, 'Georgia').replace(/url\(fonts\//g, 'url(../../node_modules/katex/dist/fonts/');
if (/Times New Roman/.test(site)) throw new Error('KaTeX stylesheet still names Times New Roman');
await writeFile(new URL('../src/styles/katex.css', import.meta.url), '/* Generated by scripts/equations.mjs from katex.min.css: Georgia replaces Times New Roman as the fallback. */\n' + site);
console.log('wrote src/styles/katex.css');
